#!/usr/bin/env python3
"""Regenerate the docs roster from the theme files, plan files, role cards and icons.

Writes docs/roster.md, docs/assets/icons/<theme>/<id>.png (96px) and docs/assets/banner.png.
Run from the repository root after changing a theme, a plan, a role card or an icon:

    python3 tools/gen-roster-docs.py

Needs Pillow for the images (pip install pillow). Never edit docs/roster.md by hand.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES = ["mahabharat", "avengers", "hogwarts", "middle-earth", "plain"]
PLANS = [("Pro", "sabha.pro.conf"), ("Max 5x", "sabha.max5.conf"), ("Max 20x", "sabha.max20.conf")]
FAN = {"avengers", "hogwarts", "middle-earth"}


def path(*p):
    return os.path.join(ROOT, *p)


def read(p):
    with open(path(p), encoding="ascii") as f:
        return f.read()


def theme_rows(theme):
    rows = []
    for line in read("themes/%s.theme" % theme).splitlines():
        if line.strip() and not line.startswith("#"):
            rid, name, colour, persona = line.split("|", 3)
            rows.append({"id": rid, "name": name, "colour": colour, "persona": persona})
    return rows


def theme_title(theme):
    m = re.search(r"^# Theme: (.+)$", read("themes/%s.theme" % theme), re.M)
    return m.group(1) if m else theme


def labels():
    return dict(re.findall(r'^SABHA_LABEL_(\w+)="([^"]*)"', read("sabha.max20.conf"), re.M))


def plan_roles(conf):
    """{id: 'pane' | 'lazy' | 'on demand'} from the plan's SABHA_ROSTER."""
    m = re.search(r'^SABHA_ROSTER="([^"]*)"', read(conf), re.M)
    out = {}
    for entry in m.group(1).split():
        parts = entry.split(":")
        flags = parts[-1] if len(parts) >= 5 else ""
        out[parts[0]] = "on demand" if "ondemand" in flags else "lazy" if "lazy" in flags else "pane"
    return out


def job(rid):
    """The card's opening paragraph, which may wrap over several lines."""
    para = read("template/impl/protocol/%s.md" % rid).split("\n\n")[1]
    return " ".join(para.split())


def icon(theme, rid, size=48):
    return '<img src="{{ \'/assets/icons/%s/%s.png\' | relative_url }}" width="%d" height="%d" alt="">' % (
        theme, rid.lower(), size, size)


def write_roster():
    lab = labels()
    plans = [(n, plan_roles(c)) for n, c in PLANS]
    base = theme_rows("mahabharat")
    out = [
        "---",
        "title: Roster",
        "nav_order: 8",
        "---",
        "",
        "<!-- generated by tools/gen-roster-docs.py from themes/, the plan files and template/impl/protocol/;",
        "     do not edit by hand -->",
        "",
        "# The 20 roles",
        "",
        "Every role is a Claude Code session with its own name, model, effort, inbox and status file. The id (left) is",
        "what the scripts and plan files use; a [theme](themes.md) only changes the name, colour and persona you see.",
        "A plan starts a role in a pane, starts it lazily when a brief lands, or only on demand; a dash means the",
        "plan does not include it.",
        "",
        "| | Role | Label | Job | %s |" % " | ".join(n for n, _ in plans),
        "| --- | --- | --- | --- | %s |" % " | ".join("---" for _ in plans),
    ]
    for r in base:
        rid = r["id"]
        cells = [roles.get(rid, "-") for _, roles in plans]
        out.append("| %s | **%s** | %s | %s | %s |" % (
            icon("mahabharat", rid), rid, lab.get(rid, ""), job(rid), " | ".join(cells)))
    out += ["", "Each role's full card is in `template/impl/protocol/<Id>.md`.", "", "# Themes side by side", ""]
    out.append("| Role | %s |" % " | ".join(theme_title(t) for t in THEMES))
    out.append("| --- | %s |" % " | ".join("---" for _ in THEMES))
    rows = {t: theme_rows(t) for t in THEMES}
    for i, r in enumerate(base):
        cells = []
        for t in THEMES:
            tr = rows[t][i]
            cells.append("%s<br>%s" % (icon(t, tr["id"], 40), tr["name"]))
        out.append("| %s | %s |" % (lab.get(r["id"], r["id"]), " | ".join(cells)))
    for t in THEMES:
        out += ["", "## %s" % theme_title(t), ""]
        if t in FAN:
            out += ["Fan theme. Character names belong to their owners; claude-sabha is not affiliated with or",
                    "endorsed by them. The icons are generic symbols, not likenesses or logos.", ""]
        out += ["| | Name | Stands in for | Persona |", "| --- | --- | --- | --- |"]
        for tr in rows[t]:
            out.append('| %s | <span style="color:%s">**%s**</span> | %s | %s |' % (
                icon(t, tr["id"], 40), tr["colour"], tr["name"], lab.get(tr["id"], tr["id"]), tr["persona"]))
    with open(path("docs/roster.md"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def write_images():
    from PIL import Image
    for t in THEMES:
        os.makedirs(path("docs/assets/icons", t), exist_ok=True)
        for r in theme_rows(t):
            src = path("icons", t, r["id"].lower() + ".png")
            Image.open(src).convert("RGB").resize((96, 96), Image.LANCZOS).save(
                path("docs/assets/icons", t, r["id"].lower() + ".png"), optimize=True)
    # banner: the five themes as five rows of 20 icons
    tile, gap = 56, 6
    w = 20 * (tile + gap) + gap
    h = len(THEMES) * (tile + gap) + gap
    banner = Image.new("RGB", (w, h), (13, 17, 23))
    for j, t in enumerate(THEMES):
        for i, r in enumerate(theme_rows(t)):
            im = Image.open(path("icons", t, r["id"].lower() + ".png")).convert("RGB").resize((tile, tile), Image.LANCZOS)
            banner.paste(im, (gap + i * (tile + gap), gap + j * (tile + gap)))
    banner.save(path("docs/assets/banner.png"), optimize=True)


if __name__ == "__main__":
    write_roster()
    if "--no-images" not in sys.argv:
        write_images()
    print("wrote docs/roster.md, docs/assets/icons/, docs/assets/banner.png")
